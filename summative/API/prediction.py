"""FastAPI service that predicts the retail price (RWF per kg) of a food item in Rwanda.

Routes
------
POST /predict  -> predicted price for one market / commodity / month
POST /retrain  -> upload a CSV of new rows; the model is refitted and used straight away
GET  /docs     -> Swagger UI generated by FastAPI

Run locally from summative/API:
    uv run uvicorn prediction:app --reload
"""
import io
import threading
from dataclasses import dataclass
from pathlib import Path

import joblib
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field, field_validator
from sklearn.base import clone

MODEL_PATH = Path(__file__).resolve().parent / "best_model.pkl"

FEATURES = ["market", "commodity", "pricetype", "year", "month"]
CATEGORICAL = ["market", "commodity", "pricetype"]
TARGET = "price"

# Realistic limits (the data covers 2000-2026)
YEAR_MIN, YEAR_MAX = 2000, 2030
MAX_PRICE_PER_KG = 20000  # same cut-off used in the notebook


# --------------------------------------------------------------------------- #
# Model state: the model, the values it knows, and the data it was trained on
# --------------------------------------------------------------------------- #
@dataclass(frozen=True)
class ModelState:
    pipeline: object
    lookup: dict          # field -> {lowercase value: exact value the model knows}
    train_df: pd.DataFrame  # original training rows (None if the pickle has none)


def build_state(pipeline, train_df) -> ModelState:
    """Read the categories the fitted pipeline knows so inputs can be validated."""
    preprocess = pipeline.named_steps["preprocess"]
    lookup = {}
    for name, transformer, columns in preprocess.transformers_:
        if name == "cat":
            for column, categories in zip(columns, transformer.categories_):
                lookup[column] = {str(c).lower(): str(c) for c in categories}
    return ModelState(pipeline=pipeline, lookup=lookup, train_df=train_df)


def load_state() -> ModelState:
    pipeline = joblib.load(MODEL_PATH)
    data = getattr(pipeline, "training_data_", None)
    train_df = pd.DataFrame(data)[FEATURES + [TARGET]] if data else None
    return build_state(pipeline, train_df)


STATE = load_state()      # loaded from the repository at startup
_retrain_lock = threading.Lock()


# --------------------------------------------------------------------------- #
# App and CORS
# --------------------------------------------------------------------------- #
app = FastAPI(
    title="Rwanda Food Price Prediction API",
    description="Predicts the retail price per kg (RWF) of a food item from "
                "the market, commodity, price type, year and month.",
)

# CORS: browsers only let a web page call this API if its origin is listed here.
# ALLOWED: only the origins listed below (the deployed Render service, which also
#   serves Swagger UI, and local Flutter web debug servers), only GET and POST
#   (all this API uses), and only the headers the clients actually send.
# RESTRICTED: every other website is blocked, so a random site cannot call the API
#   from a visitor's browser. No wildcard "*" is used, which matters because
#   credentials are allowed: browsers refuse "*" together with credentials.
# The Flutter mobile app is not a browser, so CORS does not apply to it.
ALLOWED_ORIGINS = [
    "https://your-service.onrender.com",  # TODO Day 5: replace with the real Render URL
    "http://localhost:8080",              # local Flutter web debug (fixed --web-port)
    "http://127.0.0.1:8080",
    "http://localhost:3000",
    "http://127.0.0.1:3000",
    "http://localhost:8000",              # Swagger UI when running uvicorn locally
    "http://127.0.0.1:8000",
]

app.add_middleware(
    CORSMiddleware,
    allow_origins=ALLOWED_ORIGINS,
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
    allow_credentials=True,
)


# --------------------------------------------------------------------------- #
# /predict
# --------------------------------------------------------------------------- #
class PredictionInput(BaseModel):
    """One request. Strict types: "2020" (a string) is rejected for an int field."""

    model_config = ConfigDict(
        strict=True,
        extra="forbid",
        json_schema_extra={
            "example": {
                "market": "Kigali",
                "commodity": "Maize",
                "pricetype": "Retail",
                "year": 2024,
                "month": 6,
            }
        },
    )

    market: str = Field(..., min_length=1, max_length=100,
                        description="Market name, e.g. Kigali")
    commodity: str = Field(..., min_length=1, max_length=100,
                           description="Food item, e.g. Maize")
    pricetype: str = Field(..., min_length=1, max_length=50,
                           description="Retail or Wholesale")
    year: int = Field(..., ge=YEAR_MIN, le=YEAR_MAX, description="Year, 2000 to 2030")
    month: int = Field(..., ge=1, le=12, description="Month number, 1 to 12")

    @field_validator("market", "commodity", "pricetype")
    @classmethod
    def must_be_known(cls, value: str, info):
        """Reject values the model has never seen instead of returning a meaningless price."""
        known = STATE.lookup[info.field_name]
        match = known.get(value.strip().lower())
        if match is None:
            examples = ", ".join(sorted(known.values())[:8])
            raise ValueError(
                f"Unknown {info.field_name} '{value}'. Examples of valid values: {examples}"
            )
        return match


@app.post("/predict")
def predict(payload: PredictionInput):
    row = pd.DataFrame([payload.model_dump()])[FEATURES]
    price = float(STATE.pipeline.predict(row)[0])
    return {
        "predicted_price": round(price, 2),
        "currency": "RWF",
        "unit": "per kg",
        "inputs": payload.model_dump(),
    }


# --------------------------------------------------------------------------- #
# /retrain
# --------------------------------------------------------------------------- #
def prepare_new_rows(df: pd.DataFrame) -> tuple[pd.DataFrame, int]:
    """Turn an uploaded CSV into clean training rows. Returns (rows, number ignored)."""
    df.columns = [str(c).strip().lower() for c in df.columns]

    # Accept the raw WFP layout (date, unit, ...) as well as year/month columns
    if "date" in df.columns and not {"year", "month"}.issubset(df.columns):
        dates = pd.to_datetime(df["date"], errors="coerce")
        df["year"], df["month"] = dates.dt.year, dates.dt.month
    if "unit" in df.columns:  # the model predicts prices per KG only
        df = df[df["unit"].astype(str).str.strip().str.upper() == "KG"]

    missing = [c for c in FEATURES + [TARGET] if c not in df.columns]
    if missing:
        raise HTTPException(
            status_code=400,
            detail=f"CSV is missing required column(s): {', '.join(missing)}. "
                   f"Needed: market, commodity, pricetype, price and either "
                   f"year + month or date.",
        )

    total = len(df)
    df = df[FEATURES + [TARGET]].copy()
    for column in ["year", "month", TARGET]:
        df[column] = pd.to_numeric(df[column], errors="coerce")
    for column in CATEGORICAL:
        df[column] = df[column].astype("string").str.strip()
    df = df.dropna()

    df["year"], df["month"] = df["year"].astype(int), df["month"].astype(int)
    df = df[
        df["month"].between(1, 12)
        & df["year"].between(YEAR_MIN, YEAR_MAX)
        & (df[TARGET] > 0)
        & (df[TARGET] < MAX_PRICE_PER_KG)
    ]
    for column in CATEGORICAL:  # reuse the spelling the model already knows
        known = STATE.lookup[column]
        df[column] = df[column].map(lambda v: known.get(v.lower(), v)).astype(object)

    return df.reset_index(drop=True), total - len(df)


@app.post("/retrain")
def retrain(file: UploadFile = File(...)):
    """Upload a CSV of new rows. The model is refitted on the original data plus the
    new rows and replaces the one used by /predict immediately (no redeploy)."""
    global STATE

    if STATE.train_df is None:
        raise HTTPException(
            status_code=500,
            detail="best_model.pkl was saved without its training data, so it cannot "
                   "be refitted. Re-run the notebook's save cell and replace the file.",
        )
    try:
        uploaded = pd.read_csv(io.BytesIO(file.file.read()))
    except Exception:
        raise HTTPException(status_code=400, detail="Could not read the file as a CSV.")

    new_rows, ignored = prepare_new_rows(uploaded)
    if new_rows.empty:
        raise HTTPException(status_code=400,
                            detail="No valid rows found in the uploaded CSV.")

    with _retrain_lock:
        current = STATE
        combined = pd.concat([current.train_df, new_rows], ignore_index=True)
        # Random forest: refit from scratch on the original data plus the new rows.
        # clone() keeps the hyperparameters; the encoder is refitted, so a new
        # market or commodity in the upload becomes a valid input.
        refitted = clone(current.pipeline)
        refitted.fit(combined[FEATURES], combined[TARGET])
        STATE = build_state(refitted, combined)

    return {
        "message": "Model retrained and now used by /predict.",
        "new_rows_used": len(new_rows),
        "rows_ignored": ignored,
        "total_training_rows": len(combined),
    }
